namespace StringFunctions.Russian;

/// <summary>
/// Грамматическая форма существительного, согласуемого с числом в русском языке.
/// </summary>
/// <remarks>
/// Русский язык использует три формы при счёте, выбор которых зависит
/// от последних одной-двух цифр числа.
/// </remarks>
public enum RussianPluralForm
{
  /// <summary>
  /// Форма для чисел, оканчивающихся на <c>1</c> (кроме оканчивающихся на <c>11</c>):
  /// <c>1</c>, <c>21</c>, <c>101</c>. Пример: «1 яблоко».
  /// </summary>
  One,

  /// <summary>
  /// Форма для чисел, оканчивающихся на <c>2</c>–<c>4</c> (кроме <c>12</c>–<c>14</c>):
  /// <c>2</c>, <c>3</c>, <c>4</c>, <c>22</c>. Пример: «2 яблока».
  /// </summary>
  Few,

  /// <summary>
  /// Форма для остальных чисел: <c>0</c>, <c>5</c>–<c>20</c>, <c>11</c>–<c>14</c>, <c>25</c>.
  /// Пример: «5 яблок».
  /// </summary>
  Many
}
