namespace StringFunctions.Russian;

/// <summary>
/// Падеж русского языка, в котором записывается числительное.
/// </summary>
/// <remarks>
/// Порядок значений соответствует традиционному порядку падежей и используется
/// как индекс во внутренних таблицах склонения; изменять его нельзя.
/// </remarks>
public enum RussianCase
{
  /// <summary>Именительный (кто? что?): «двадцать пять».</summary>
  Nominative = 0,

  /// <summary>Родительный (кого? чего?): «двадцати пяти».</summary>
  Genitive = 1,

  /// <summary>Дательный (кому? чему?): «двадцати пяти».</summary>
  Dative = 2,

  /// <summary>
  /// Винительный (кого? что?): «двадцать пять».
  /// Формируется для неодушевлённого счёта (совпадает с именительным,
  /// кроме женского рода единицы: «одну»).
  /// </summary>
  Accusative = 3,

  /// <summary>Творительный (кем? чем?): «двадцатью пятью».</summary>
  Instrumental = 4,

  /// <summary>Предложный (о ком? о чём?): «двадцати пяти».</summary>
  Prepositional = 5
}
