namespace StringFunctions.Russian;

/// <summary>
/// Грамматический род, влияющий на форму числительных «один» и «два» в русском языке.
/// </summary>
/// <remarks>
/// Род влияет только на единицы: <c>один/одна/одно</c> и <c>два/две/два</c>.
/// Остальные числительные от рода не зависят.
/// </remarks>
public enum RussianGender
{
  /// <summary>Мужской род: «один», «два» (один рубль, два стола).</summary>
  Masculine,

  /// <summary>Женский род: «одна», «две» (одна копейка, две тысячи).</summary>
  Feminine,

  /// <summary>Средний род: «одно», «два» (одно слово).</summary>
  Neuter
}
